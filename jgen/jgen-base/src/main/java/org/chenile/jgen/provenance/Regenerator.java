package org.chenile.jgen.provenance;

import org.chenile.jgen.blueprints.BlueprintConfig;
import org.chenile.jgen.blueprints.BlueprintExecutor;
import org.chenile.jgen.blueprints.BlueprintPayloadValidator;
import org.chenile.jgen.blueprints.PayloadIssue;
import org.chenile.jgen.blueprints.PayloadValidation;
import org.chenile.jgen.blueprints.Registry;
import org.chenile.jgen.config.Config;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import java.util.TreeMap;
import java.util.TreeSet;

/**
 * Re-cuts a generated project from its {@code .jgen/generation.json} with the blueprint version now on the
 * classpath, into a separate folder, and classifies every file by comparing three states: as first generated
 * (the recorded hashes), as it is now (the project on disk) and as the current blueprint generates it.
 *
 * <p>It never modifies the original project. The {@link RegenerationReport} says which files are safe to take
 * as they are, which the user changed but the blueprint did not, and which changed on both sides and need a merge,
 * by a person or an agent.</p>
 */
public final class Regenerator {

    public enum Change {
        /** Unchanged by the user, changed by the blueprint: safe to take the regenerated file. */
        SAFE_UPDATE,
        /** Changed by the user, unchanged by the blueprint: keep the user's file. */
        KEEP_USER,
        /** Changed by the user and by the blueprint, or added on both sides with different content: merge. */
        CONFLICT,
        /** New in the blueprint and absent from the project: safe to add. */
        NEW_FILE,
        /** Dropped by the blueprint and unchanged by the user: safe to delete. */
        SAFE_DELETE,
        /** Dropped by the blueprint but changed by the user: decide by hand. */
        DELETE_CONFLICT,
        /** Deleted by the user, still generated by the blueprint: the user's deletion stands unless they want it back. */
        USER_DELETED
    }

    public record FileChange(String path, Change change) { }

    public record RegenerationReport(Path project, Path regenerated, GenerationRecord previous,
                                     GenerationRecord current, List<FileChange> changes) {
        public List<FileChange> only(Change change) {
            return changes.stream().filter(c -> c.change() == change).toList();
        }
    }

    private final BlueprintExecutor executor = new BlueprintExecutor();

    /**
     * @param projectDir   a project generated by JGen (it contains {@code .jgen/generation.json})
     * @param outputRoot   an empty or new folder to regenerate into; the project appears under it with its own name
     * @param configOverride the config to use instead of the recorded one, or null to reuse the recorded config
     */
    public RegenerationReport regenerate(Path projectDir, Path outputRoot, Config configOverride) throws Exception {
        Path project = projectDir.toAbsolutePath().normalize();
        GenerationRecord previous = ProvenanceRecorder.read(project);
        BlueprintConfig blueprint = Registry.blueprints.get(previous.blueprint.name);
        if (blueprint == null)
            throw new IllegalArgumentException("Blueprint " + previous.blueprint.name + " is not on the classpath");
        Config config = configOverride != null ? configOverride
                : ProvenanceRecorder.MAPPER.convertValue(previous.config, Config.class);

        Map<String, Object> inputs = new LinkedHashMap<>(previous.inputs);
        for (Map.Entry<String, String> file : previous.fileInputs.entrySet()) {
            inputs.put(file.getKey(), project.resolve(file.getValue()).toString());
        }
        PayloadValidation validation = BlueprintPayloadValidator.validate(blueprint, config, inputs);
        if (!validation.valid()) {
            throw new IllegalArgumentException("The recorded inputs are not valid for the current version of blueprint "
                    + blueprint.name + ": " + validation.errors().stream().map(PayloadIssue::toString).toList());
        }
        Path root = outputRoot.toAbsolutePath().normalize();
        Files.createDirectories(root);
        Map<String, Object> map = new HashMap<>(validation.inputs());
        map.put("destFolder", root.toString());
        executor.execute(blueprint, config, map);

        Path regenerated = ProvenanceRecorder.projectDirectory(blueprint, map);
        GenerationRecord current = Files.isRegularFile(regenerated.resolve(ProvenanceRecorder.RECORD_FOLDER)
                .resolve(ProvenanceRecorder.RECORD_FILE)) ? ProvenanceRecorder.read(regenerated) : null;
        Map<String, String> next = current != null ? current.files : ProvenanceRecorder.manifest(regenerated);
        List<FileChange> changes = classify(previous.files, ProvenanceRecorder.manifest(project), next);
        return new RegenerationReport(project, regenerated, previous, current, changes);
    }

    /** Three-way classification of every path known to the original generation or to the new one. */
    static List<FileChange> classify(Map<String, String> base, Map<String, String> mine, Map<String, String> theirs) {
        TreeSet<String> paths = new TreeSet<>(base.keySet());
        paths.addAll(theirs.keySet());
        List<FileChange> changes = new ArrayList<>();
        for (String path : paths) {
            String b = base.get(path), m = mine.get(path), t = theirs.get(path);
            boolean userChanged = !Objects.equals(b, m);
            boolean blueprintChanged = !Objects.equals(b, t);
            Change change;
            if (!blueprintChanged) {
                if (!userChanged) continue;
                change = m == null ? Change.USER_DELETED : Change.KEEP_USER;
            } else if (t == null) {
                change = m == null ? null : userChanged ? Change.DELETE_CONFLICT : Change.SAFE_DELETE;
            } else if (b == null) {
                change = m == null ? Change.NEW_FILE : Objects.equals(m, t) ? null : Change.CONFLICT;
            } else if (m == null) {
                change = Change.USER_DELETED;
            } else if (!userChanged || Objects.equals(m, t)) {
                change = Objects.equals(m, t) ? null : Change.SAFE_UPDATE;
            } else {
                change = Change.CONFLICT;
            }
            if (change != null) changes.add(new FileChange(path, change));
        }
        return changes;
    }

    /** Writes the report as JSON next to the regenerated project, for agents and tools. */
    public static Path writeReport(RegenerationReport report) throws IOException {
        Map<String, Object> json = new LinkedHashMap<>();
        json.put("project", report.project().toString());
        json.put("regenerated", report.regenerated().toString());
        json.put("blueprint", report.previous().blueprint.name);
        json.put("fromVersion", version(report.previous()));
        json.put("toVersion", report.current() == null ? null : version(report.current()));
        Map<String, List<String>> byChange = new TreeMap<>();
        for (FileChange change : report.changes())
            byChange.computeIfAbsent(change.change().name(), k -> new ArrayList<>()).add(change.path());
        json.put("changes", byChange);
        Path file = report.regenerated().getParent().resolve(report.regenerated().getFileName() + ".regeneration.json");
        ProvenanceRecorder.MAPPER.writeValue(file.toFile(), json);
        return file;
    }

    private static String version(GenerationRecord record) {
        GenerationRecord.BlueprintRef ref = record.blueprint;
        return ref.artifactVersion != null ? ref.artifactVersion : ref.version;
    }
}
