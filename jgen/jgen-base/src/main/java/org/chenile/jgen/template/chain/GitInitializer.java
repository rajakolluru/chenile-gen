package org.chenile.jgen.template.chain;

import org.apache.commons.text.StringSubstitutor;
import org.chenile.jgen.blueprints.BlueprintConfig;
import org.chenile.jgen.provenance.ProvenanceRecorder;
import org.chenile.jgen.template.model.TemplateContext;
import org.chenile.jgen.util.GitRepository;
import org.chenile.owiz.Command;

import java.nio.file.Path;
import java.util.Map;

/**
 * Makes a freshly generated project a local Git repository, when the input map has {@code initGit=true}. A
 * blueprint either asks for {@code initGit} as an input or sets it from a hook.
 *
 * <ul>
 *   <li>Always: {@code git init}, branch {@code main}, everything added, one commit (including {@code .jgen/}).</li>
 *   <li>If the blueprint names a {@code gitRepositoryField} (an input with validation GITHUB_REPOSITORY) and that
 *       input has a value: the GitHub repository is added as the {@code origin} remote, so only creating it on GitHub
 *       and pushing are left.</li>
 * </ul>
 * Nothing is created on GitHub and nothing is pushed. Runs for top-level generations only, after the generation
 * record and before the blueprint's final hook. Records the outcome in the map as {@code gitInitialised},
 * {@code gitCommitted} and {@code gitRemote} for that hook.
 */
public class GitInitializer implements Command<TemplateContext> {
    public static final String INIT_GIT = "initGit";

    @Override
    public void execute(TemplateContext context) {
        if (context.isChild() || !enabled(context.map.get(INIT_GIT))) return;
        BlueprintConfig blueprint = context.blueprintConfig;
        Map<String, Object> map = context.map;
        Path project = ProvenanceRecorder.projectDirectory(blueprint, map);

        GitRepository.Result git = GitRepository.initialise(project, commitMessage(blueprint, map));
        String repository = repository(blueprint, map);
        String remote = repository == null ? null : remoteUrl(repository, map.get("gitRemoteProtocol"));
        String remoteProblem = null;
        if (git.initialised() && remote != null) remoteProblem = GitRepository.addRemote(project, "origin", remote);

        map.put("gitInitialised", git.initialised());
        map.put("gitCommitted", git.committed());
        if (remote != null && remoteProblem == null && git.initialised()) map.put("gitRemote", remote);
        System.out.println(report(project, git, repository, remote, remoteProblem));
    }

    static boolean enabled(Object flag) {
        return Boolean.TRUE.equals(flag) || "true".equalsIgnoreCase(String.valueOf(flag));
    }

    static String repository(BlueprintConfig blueprint, Map<String, Object> map) {
        if (blueprint.gitRepositoryField == null) return null;
        Object value = map.get(blueprint.gitRepositoryField);
        return value == null || value.toString().isBlank() ? null : value.toString().trim();
    }

    static String remoteUrl(String repository, Object protocol) {
        return "https".equalsIgnoreCase(String.valueOf(protocol))
                ? "https://github.com/" + repository + ".git"
                : "git@github.com:" + repository + ".git";
    }

    private static String commitMessage(BlueprintConfig blueprint, Map<String, Object> map) {
        if (blueprint.gitCommitMessage != null && !blueprint.gitCommitMessage.isBlank())
            return new StringSubstitutor(map).replace(blueprint.gitCommitMessage);
        return "Initial " + blueprint.name + " project, generated by JGen";
    }

    static String report(Path project, GitRepository.Result git, String repository, String remote, String remoteProblem) {
        String g = "git -C " + project;
        StringBuilder out = new StringBuilder();
        if (git.committed()) {
            out.append("Git repository ready: ").append(project).append(" (branch main, 1 commit)\n");
        } else if (git.initialised()) {
            out.append("Git repository created in ").append(project).append(" with the files staged.\n  ")
               .append(git.detail()).append('\n');
        } else {
            out.append("No Git repository was created in ").append(project).append(": ").append(git.detail())
               .append("\n  To do it yourself: ").append(g).append(" init && ").append(g)
               .append(" symbolic-ref HEAD refs/heads/main && ").append(g).append(" add -A && ").append(g)
               .append(" commit -m \"Initial commit\"\n");
            return out.toString().stripTrailing();
        }
        if (git.nested())
            out.append("  Note: it is inside another Git working tree; the new repository is separate from it.\n");
        if (remote != null && remoteProblem == null) {
            out.append("Remote origin: ").append(remote).append('\n')
               .append("Next:\n")
               .append("  1. Create an empty repository on GitHub: ").append(repository)
               .append(" (no README, licence or .gitignore)\n")
               .append("  2. ").append(g).append(" push -u origin main");
        } else {
            if (remoteProblem != null) out.append("  ").append(remoteProblem).append('\n');
            out.append("To publish it: ").append(g).append(" remote add origin <url> && ").append(g)
               .append(" push -u origin main");
        }
        return out.toString();
    }
}
